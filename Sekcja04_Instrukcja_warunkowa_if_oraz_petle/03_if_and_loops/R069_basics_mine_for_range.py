# R69. Pętla for z range

# range (end) / sekwencja od 0 do end-1
for v in range(5): # [0,1,2,3,4]
    print(v)

print("")

# range (start, end) / sekwencja od start do (end-1)
for v in range(3,6): # [3,4,5]
    print(v)

print("")

# range (start, end, step) / sekwencja od start do (end-1) z krokiem step
for v in range(2,9,2): # [2,4,6,8]
    print(v)