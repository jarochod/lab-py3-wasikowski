# operatory przypisania

a = 12

a += 1;   print(a);  # a = a + 1    13
a -= 1;   print(a);  # a = a - 1    12
a *= 2;   print(a);  # a = a * 2    24
a /= 12;  print(a);  # a = a / 2     2
a %= 2;   print(a);  # a = a % 2     0
a += 3;   print(a);  # a = a + 3     3
a **= 3;  print(a);  # a = a*a*a    27
a //= 20; print(a);  # a = a//20     1
 
