# R37. Operatory arytmetyczne

a = 12
b = 3

result = a + b; print(result); # 15
result = a - b; print(result); # 9
result = a * b; print(result); # 36
result = a / b; print(result); # 4.0
result = a % b; print(result); # 0
result = a % 9; print(result); # 3
result = a ** b; print(result); # 1728
result = a // b; print(result); # 4
result = 20 // 3; print(result); # 6