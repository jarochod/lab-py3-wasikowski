# R10. Typy danych oraz liczby całkowite zmienoprzecinkowe zespolone

numInt = 1000 # liczba całkowita
print(numInt)
print( type(numInt) ) # <class 'int'>

numFloat = 3.14 # liczba rzeczywista
print(numFloat) # <class 'float'>
print( type(numFloat) )

numComplex = 5 + 2j
print(numComplex)
print( type(numComplex) )